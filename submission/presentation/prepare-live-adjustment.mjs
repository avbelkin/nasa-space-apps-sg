import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
const root=import.meta.dirname;
const require=createRequire(path.join(process.env.RUNTIME_NODE_MODULES,'__live_crop__.cjs'));
const sharp=require('sharp');
const hash=b=>crypto.createHash('sha256').update(b).digest('hex');
const original='live-adjustment.png';
const input=await fs.readFile(path.join(root,'assets/screenshots',original));
const crop={left:986,top:365,width:494,height:63};
const output=await sharp(input).extract(crop).png({compressionLevel:9}).toBuffer();
await fs.writeFile(path.join(root,'assets/evidence',original),output);
const manifestPath=path.join(root,'assets/evidence/manifest.json');
const manifest=JSON.parse(await fs.readFile(manifestPath,'utf8'));
manifest.images=manifest.images.filter(item=>item.name!=='live-adjustment');
manifest.images.push({name:'live-adjustment',original,file:original,width:crop.width,height:crop.height,bytes:output.length,crop,sourceSha256:hash(input),sha256:hash(output),provenance:'../screenshots/live-adjustment.json'});
await fs.writeFile(manifestPath,JSON.stringify(manifest,null,2)+'\n');
await fs.writeFile(path.join(root,'assets/screenshots/live-adjustment.json'),JSON.stringify({source:'Team-provided Screenshot 2026-11-15 at 22.28.33.png',capturedAt:'2026-11-15T14:28:33Z',timestampBasis:'Original screenshot filename in the team browser timezone, Asia/Singapore (UTC+8).',userAuthorization:'User explicitly selected this existing CAMS screenshot for the presentation.',sourceSha256:hash(input),crop,content:'CAMS context for NOAA-20 at 14:16: 1.28x study baseline detection odds; full experimental-model notice retained. No values altered.',deployment:'The exact deployment is not recorded by the team screenshot; no commit identity is claimed.'},null,2)+'\n');
console.log('Prepared the team-approved CAMS adjustment crop with provenance.');
